/* ==========================================================================
   Tokyo & Seoul Through My Eyes
   Renders the page from data/site-data.js (generated by tools/build-data.sh).
   Nothing here holds content - to change words, edit data/places.json.
   ========================================================================== */
(function () {
  'use strict';

  var SITE   = window.SITE_PLACES;
  var PHOTOS = window.SITE_PHOTOS || [];

  if (!SITE) {
    document.getElementById('main').innerHTML =
      '<div class="wrap" style="padding:6rem 0"><h2>Site data did not load.</h2>' +
      '<p>Run <code>tools/build-data.sh</code> to regenerate <code>data/site-data.js</code>.</p></div>';
    return;
  }

  var $  = function (s, r) { return (r || document).querySelector(s); };
  var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  /* paragraphs: myWords uses \n\n between paragraphs */
  function paras(text) {
    if (!text) return '';
    return String(text).split(/\n\s*\n/).map(function (p) {
      return '<p>' + esc(p.trim()) + '</p>';
    }).join('');
  }

  function photosFor(placeId) {
    return PHOTOS.filter(function (p) { return p.place === placeId; });
  }

  function prettyDate(iso) {
    if (!iso) return '';
    var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
    if (!m) return iso;
    var months = ['January','February','March','April','May','June','July',
                  'August','September','October','November','December'];
    return months[Number(m[2]) - 1] + ' ' + Number(m[3]);
  }

  /* pull the first number-ish token out of a stat sentence, to set as the figure */
  function statFigure(sentence) {
    var m = /(\b\d[\d.,]*\s?(?:times|million|billion)?\b)/i.exec(sentence);
    return m ? m[1].trim() : '';
  }

  /* ---------------------------------------------------------------- header */
  var site = SITE.site || {};
  $('#meta-program').textContent = site.program || '';
  $('#meta-school').textContent  = site.school || '';
  $('#meta-dates').textContent   = site.dates || '';
  if (site.author) $('#foot-author').textContent = site.author;
  if (site.email) {
    var mail = $('#foot-email');
    mail.href = 'mailto:' + site.email;
    mail.textContent = site.email;
  } else {
    $('#foot-email').remove();
  }
  $('#foot-meta').innerHTML =
    esc(site.program || '') + '<br>' + esc(site.school || '') + ' &middot; ' + esc(site.term || '') +
    '<br>' + esc(site.dates || '');

  if (site.poster) {
    var poster = $('#hero-poster-img');
    var posterRec = PHOTOS.filter(function (p) { return p.src === site.poster; })[0];
    poster.src = site.poster;
    poster.alt = 'Program poster for ' + (site.program || 'the program');
    if (posterRec) { poster.width = posterRec.width; poster.height = posterRec.height; }
  }

  /* ------------------------------------------------------------------ hero */
  (function heroStage() {
    var wanted = [
      'seoul/gyeongbokgung/01-geunjeongjeon-throne-hall',
      'tokyo/shibuya/02-shibuya-crossing-night',
      'seoul/han-river-cruise/02-sunset-and-gull',
      'tokyo/teamlab-planets/02-red-spheres-overhead',
      'seoul/seodaemun-prison/02-courtyard-and-taegukgi'
    ];
    var stage = $('#hero-stage');
    var picks = wanted.map(function (id) {
      return PHOTOS.filter(function (p) { return p.id === id; })[0];
    }).filter(Boolean);
    if (!picks.length) picks = PHOTOS.slice(0, 5);

    picks.forEach(function (p, i) {
      var img = new Image();
      img.src = p.src;
      img.alt = '';
      img.decoding = 'async';
      if (i === 0) { img.className = 'is-on'; img.loading = 'eager'; }
      else { img.loading = 'lazy'; }
      stage.appendChild(img);
    });

    if (reduceMotion || picks.length < 2) return;
    var i = 0, imgs = stage.querySelectorAll('img');
    setInterval(function () {
      imgs[i].classList.remove('is-on');
      i = (i + 1) % imgs.length;
      imgs[i].classList.add('is-on');
    }, 6500);
  }());

  /* ----------------------------------------------------------------- stats */
  (function stats() {
    var tc = SITE.twoCities;
    if (!tc) return;
    $('#stats-title').textContent = tc.title || 'Two countries, two capitals';
    $('#stats-note').textContent = tc.note || '';
    $('#stats-list').innerHTML = (tc.facts || []).map(function (f) {
      var fig = statFigure(f);
      return '<li>' + (fig ? '<b>' + esc(fig) + '</b>' : '') + '<span>' + esc(f) + '</span></li>';
    }).join('');
  }());

  /* ------------------------------------------------------------- photo html */
  /* width/height are always emitted so the browser reserves the exact box
     before the image loads - without them, lazy images cause layout jumps. */
  function dims(photo) {
    return ' width="' + (photo.width || '') + '" height="' + (photo.height || '') + '"';
  }

  function shotButton(photo, sizes) {
    return '<button type="button" class="shot" data-photo="' + esc(photo.id) + '" ' +
             'aria-label="Open photograph: ' + esc(photo.alt) + '">' +
             '<img src="' + esc(photo.thumb) + '" ' +
                  'srcset="' + esc(photo.thumb) + ' 700w, ' + esc(photo.src) + ' 1800w" ' +
                  'sizes="' + sizes + '"' + dims(photo) + ' ' +
                  'alt="' + esc(photo.alt) + '" loading="lazy" decoding="async">' +
           '</button>';
  }

  function shotsHtml(list, note) {
    if (!list.length) return '';
    var lead = list[0], rest = list.slice(1);
    var html = '<div class="shots">' +
      '<figure class="shots--lead">' + shotButton(lead, '(min-width: 900px) 760px, 92vw') +
        '<figcaption>' + esc(lead.caption) + '</figcaption></figure>';
    if (rest.length) {
      html += '<div class="shots__rest">' + rest.map(function (p) {
        return '<figure>' + shotButton(p, '(min-width: 900px) 240px, 45vw') +
               '<figcaption>' + esc(p.caption) + '</figcaption></figure>';
      }).join('') + '</div>';
    }
    if (note) html += '<p class="shots__note">' + esc(note) + '</p>';
    return html + '</div>';
  }

  function linksHtml(links) {
    if (!links || !links.length) return '';
    return '<ul class="learn__links">' + links.map(function (l) {
      return '<li><a href="' + esc(l.url) + '" target="_blank" rel="noopener noreferrer">' +
             esc(l.label) + '</a></li>';
    }).join('') + '</ul>';
  }

  function learnHtml(place) {
    var hasFacts = place.facts && place.facts.length;
    var hasLinks = place.learnMore && place.learnMore.length;
    if (!hasFacts && !hasLinks) return '';
    return '<details class="learn"><summary>Learn more</summary><div class="learn__body">' +
      (hasFacts ? '<ul>' + place.facts.map(function (f) { return '<li>' + esc(f) + '</li>'; }).join('') + '</ul>' : '') +
      linksHtml(place.learnMore) +
      '</div></details>';
  }

  function asideHtml(a) {
    if (!a) return '';
    return '<div class="aside">' +
      '<h4 class="aside__title">' + esc(a.title) + '</h4>' +
      (a.nameLocal ? '<p class="aside__local">' + esc(a.nameLocal) + '</p>' : '') +
      (a.myWords ? '<p class="aside__words">' + esc(a.myWords) + '</p>' : '') +
      (a.facts && a.facts.length
        ? '<ul>' + a.facts.map(function (f) { return '<li>' + esc(f) + '</li>'; }).join('') + '</ul>'
        : '') +
      linksHtml(a.learnMore) +
      '</div>';
  }

  function dishesHtml(dishes) {
    if (!dishes || !dishes.length) return '';
    return '<dl class="dishes">' + dishes.map(function (d) {
      return '<div><dt>' + esc(d.name) +
             (d.nameLocal ? '<span>' + esc(d.nameLocal) + '</span>' : '') + '</dt>' +
             '<dd>' + esc(d.note) + '</dd></div>';
    }).join('') + '</dl>';
  }

  /* ------------------------------------------------------------------ plot */
  function plotHtml(city) {
    var pts = [];
    city.places.forEach(function (pl) {
      photosFor(pl.id).forEach(function (ph) {
        if (ph.gps) pts.push({ lat: ph.gps[0], lon: ph.gps[1], place: pl.name, id: pl.id });
      });
    });
    if (pts.length < 3) return '';

    var lats = pts.map(function (p) { return p.lat; });
    var lons = pts.map(function (p) { return p.lon; });
    var minLat = Math.min.apply(null, lats), maxLat = Math.max.apply(null, lats);
    var minLon = Math.min.apply(null, lons), maxLon = Math.max.apply(null, lons);
    var padLat = (maxLat - minLat) * 0.12 || 0.01;
    var padLon = (maxLon - minLon) * 0.12 || 0.01;
    minLat -= padLat; maxLat += padLat; minLon -= padLon; maxLon += padLon;

    var W = 1000, H = 420;
    var circles = pts.map(function (p) {
      var x = ((p.lon - minLon) / (maxLon - minLon)) * W;
      var y = H - ((p.lat - minLat) / (maxLat - minLat)) * H;
      return '<circle cx="' + x.toFixed(1) + '" cy="' + y.toFixed(1) + '" r="7" ' +
             'tabindex="0" role="button" data-goto="' + esc(p.id) + '" ' +
             'data-name="' + esc(p.place) + '"><title>' + esc(p.place) + '</title></circle>';
    }).join('');

    return '<div class="plot">' +
      '<p class="plot__label">Where I was &mdash; every geotagged photograph in ' + esc(city.name) + '</p>' +
      '<svg viewBox="0 0 ' + W + ' ' + H + '" role="img" ' +
        'aria-label="Scatter plot of ' + pts.length + ' photograph locations across ' + esc(city.name) + '">' +
        circles + '</svg>' +
      '<p class="plot__tip">Hover or focus a point to name the place; select it to jump there.</p>' +
      '</div>';
  }

  /* ---------------------------------------------------------------- cities */
  var citiesHost = $('#cities');
  var navPlaces = [];

  (SITE.cities || []).forEach(function (city, ci) {
    var sec = document.createElement('section');
    sec.className = 'city city--' + city.id;
    sec.id = city.id;

    var head =
      '<div class="wrap city__head reveal">' +
        '<p class="city__eyebrow">' + String(ci + 1).padStart(2, '0') + ' &mdash; ' + esc(city.dates || '') + '</p>' +
        '<h2 class="city__name">' + esc(city.name) +
          (city.nameLocal ? '<span>' + esc(city.nameLocal) + '</span>' : '') + '</h2>' +
        (city.intro ? '<p class="city__intro">' + esc(city.intro) + '</p>' : '') +
        plotHtml(city) +
      '</div>';

    var body = (city.places || []).map(function (place, pi) {
      var list = photosFor(place.id);
      navPlaces.push({ id: place.id, name: place.name, city: city.id });

      var metaBits = [];
      if (place.neighborhood) metaBits.push(place.neighborhood);
      if (place.dateRange) metaBits.push(place.dateRange);
      else if (place.date) metaBits.push(prettyDate(place.date));
      if (list.length) metaBits.push(list.length + (list.length === 1 ? ' photograph' : ' photographs'));

      return '<article class="place" id="place-' + esc(place.id) + '">' +
        '<div class="wrap place__grid reveal">' +
          '<header class="place__head">' +
            '<span class="place__num">' + String(pi + 1).padStart(2, '0') + '</span>' +
            '<h3 class="place__name">' + esc(place.name) +
              (place.nameLocal ? '<span class="place__local">' + esc(place.nameLocal) + '</span>' : '') +
            '</h3>' +
            (place.subtitle ? '<p class="place__sub">' + esc(place.subtitle) + '</p>' : '') +
            (metaBits.length ? '<p class="place__meta">' + esc(metaBits.join(' · ')) + '</p>' : '') +
          '</header>' +
          '<div class="place__body">' +
            (place.myWords ? '<div class="words">' + paras(place.myWords) + '</div>' : '') +
            dishesHtml(place.dishes) +
            shotsHtml(list, place.photoNote) +
            learnHtml(place) +
            (place.recommendation
              ? '<div class="rec"><b>Try this</b><p>' + esc(place.recommendation) + '</p></div>'
              : '') +
            asideHtml(place.aside) +
          '</div>' +
        '</div>' +
      '</article>';
    }).join('');

    sec.innerHTML = head + body;
    citiesHost.appendChild(sec);
  });

  /* ---------------------------------------------------------------- travel */
  (function travel() {
    var list = PHOTOS.filter(function (p) { return p.place === '99-travel'; });
    var host = $('#travel-grid');
    if (!list.length) { $('#travel').remove(); return; }
    host.innerHTML = list.map(function (p) {
      return '<figure>' +
        '<button type="button" class="shot" data-photo="' + esc(p.id) + '" ' +
          'aria-label="Open photograph: ' + esc(p.alt) + '">' +
          '<img src="' + esc(p.thumb) + '"' + dims(p) + ' alt="' + esc(p.alt) + '" ' +
               'loading="lazy" decoding="async">' +
        '</button>' +
        '<figcaption>' + esc(p.caption) + '</figcaption></figure>';
    }).join('');
  }());

  /* --------------------------------------------------------------- gallery */
  (function gallery() {
    var grid = $('#gallery-grid');
    var chips = $('#gallery-filters');
    var empty = $('#gallery-empty');
    $('#gallery-count').textContent = PHOTOS.length;

    var placeNames = {};
    (SITE.cities || []).forEach(function (c) {
      (c.places || []).forEach(function (p) { placeNames[p.id] = p.name; });
    });
    placeNames['00-program'] = 'The program';
    placeNames['99-travel'] = 'Getting there';

    var filters = [{ key: 'all', label: 'All ' + PHOTOS.length, cls: '' }];
    (SITE.cities || []).forEach(function (c) {
      var n = PHOTOS.filter(function (p) { return p.city === c.id; }).length;
      filters.push({ key: 'city:' + c.id, label: c.name + ' ' + n, cls: 'chip--' + c.id });
    });
    (SITE.cities || []).forEach(function (c) {
      (c.places || []).forEach(function (p) {
        if (photosFor(p.id).length) filters.push({ key: 'place:' + p.id, label: p.name, cls: '' });
      });
    });

    chips.innerHTML = filters.map(function (f, i) {
      return '<button type="button" class="' + f.cls + (i === 0 ? ' is-on' : '') + '" ' +
             'data-filter="' + esc(f.key) + '" aria-pressed="' + (i === 0) + '">' +
             esc(f.label) + '</button>';
    }).join('');

    function render(key) {
      var list = PHOTOS;
      if (key.indexOf('city:') === 0) {
        var c = key.slice(5);
        list = PHOTOS.filter(function (p) { return p.city === c; });
      } else if (key.indexOf('place:') === 0) {
        var pl = key.slice(6);
        list = PHOTOS.filter(function (p) { return p.place === pl; });
      }
      grid.innerHTML = list.map(function (p) {
        return '<figure>' +
          '<button type="button" class="shot" data-photo="' + esc(p.id) + '" ' +
            'aria-label="Open photograph: ' + esc(p.alt) + '">' +
            '<img src="' + esc(p.thumb) + '"' + dims(p) + ' alt="' + esc(p.alt) + '" ' +
                 'loading="lazy" decoding="async">' +
          '</button></figure>';
      }).join('');
      empty.hidden = list.length > 0;
    }

    chips.addEventListener('click', function (e) {
      var btn = e.target.closest('button[data-filter]');
      if (!btn) return;
      Array.prototype.forEach.call(chips.children, function (b) {
        b.classList.remove('is-on');
        b.setAttribute('aria-pressed', 'false');
      });
      btn.classList.add('is-on');
      btn.setAttribute('aria-pressed', 'true');
      render(btn.dataset.filter);
    });

    render('all');
  }());

  /* -------------------------------------------------------------- lightbox */
  (function lightbox() {
    var box = $('#lightbox'), img = $('#lb-img');
    var cap = $('#lb-caption'), meta = $('#lb-meta');
    var order = [], idx = 0, lastFocus = null;

    var placeNames = {};
    (SITE.cities || []).forEach(function (c) {
      (c.places || []).forEach(function (p) { placeNames[p.id] = p.name + ', ' + c.name; });
    });
    placeNames['00-program'] = 'The program';
    placeNames['99-travel'] = 'Getting there, and back';

    function show(i) {
      idx = (i + order.length) % order.length;
      var p = order[idx];
      img.src = p.src;
      img.alt = p.alt;
      cap.textContent = p.caption;
      meta.textContent = (placeNames[p.place] || p.place) + '  •  ' + (idx + 1) + ' / ' + order.length;
    }

    function open(id, scope) {
      order = scope && scope.length ? scope : PHOTOS;
      var i = 0;
      for (var k = 0; k < order.length; k++) { if (order[k].id === id) { i = k; break; } }
      lastFocus = document.activeElement;
      box.hidden = false;
      document.body.classList.add('lb-open');
      show(i);
      $('#lb-close').focus();
    }

    function close() {
      box.hidden = true;
      document.body.classList.remove('lb-open');
      img.removeAttribute('src');
      if (lastFocus && lastFocus.focus) lastFocus.focus();
    }

    document.addEventListener('click', function (e) {
      var btn = e.target.closest('button.shot[data-photo]');
      if (btn) {
        // navigate within whichever group the photo was clicked in
        var group = btn.closest('.place__body, .gallery__grid, .travel__grid');
        var scope = null;
        if (group) {
          scope = Array.prototype.map.call(group.querySelectorAll('button.shot[data-photo]'), function (b) {
            var id = b.dataset.photo;
            return PHOTOS.filter(function (p) { return p.id === id; })[0];
          }).filter(Boolean);
        }
        open(btn.dataset.photo, scope);
        return;
      }
      if (box.hidden) return;
      if (e.target === box || e.target.closest('#lb-close')) { close(); return; }
      if (e.target.closest('#lb-prev')) { show(idx - 1); return; }
      if (e.target.closest('#lb-next')) { show(idx + 1); return; }
    });

    document.addEventListener('keydown', function (e) {
      if (box.hidden) return;
      if (e.key === 'Escape') { close(); }
      else if (e.key === 'ArrowLeft') { show(idx - 1); }
      else if (e.key === 'ArrowRight') { show(idx + 1); }
      else if (e.key === 'Tab') {
        // keep focus inside the dialog
        var f = box.querySelectorAll('button');
        var first = f[0], last = f[f.length - 1];
        if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
        else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
      }
    });
  }());

  /* ------------------------------------------------------- plot interaction */
  document.addEventListener('mouseover', function (e) {
    var c = e.target.closest('circle[data-goto]');
    if (!c) return;
    var tip = c.closest('.plot').querySelector('.plot__tip');
    tip.textContent = c.dataset.name;
  });
  document.addEventListener('focusin', function (e) {
    var c = e.target.closest && e.target.closest('circle[data-goto]');
    if (!c) return;
    c.closest('.plot').querySelector('.plot__tip').textContent = c.dataset.name;
  });
  function gotoPlace(c) {
    var target = document.getElementById('place-' + c.dataset.goto);
    if (target) target.scrollIntoView({ behavior: reduceMotion ? 'auto' : 'smooth', block: 'start' });
  }
  document.addEventListener('click', function (e) {
    var c = e.target.closest('circle[data-goto]');
    if (c) gotoPlace(c);
  });
  document.addEventListener('keydown', function (e) {
    if (e.key !== 'Enter' && e.key !== ' ') return;
    var c = e.target.closest && e.target.closest('circle[data-goto]');
    if (c) { e.preventDefault(); gotoPlace(c); }
  });

  /* ---------------------------------------------------- scroll: bar, topbar */
  (function scrollUi() {
    var bar = $('#progress-bar'), top = $('#topbar');
    var links = Array.prototype.slice.call(document.querySelectorAll('.topbar__nav a'));
    var ticking = false;

    function update() {
      ticking = false;
      var h = document.documentElement.scrollHeight - window.innerHeight;
      var y = window.scrollY;
      bar.style.width = (h > 0 ? (y / h) * 100 : 0) + '%';
      top.classList.toggle('is-stuck', y > 80);

      var current = '';
      ['tokyo', 'seoul', 'gallery'].forEach(function (id) {
        var el = document.getElementById(id);
        if (el && el.getBoundingClientRect().top <= window.innerHeight * 0.45) current = id;
      });
      links.forEach(function (a) {
        a.classList.toggle('is-active', a.getAttribute('href') === '#' + current);
      });
    }

    window.addEventListener('scroll', function () {
      if (!ticking) { ticking = true; window.requestAnimationFrame(update); }
    }, { passive: true });
    update();
  }());

  /* --------------------------------------------------------------- reveals */
  (function reveals() {
    var els = document.querySelectorAll('.reveal');
    function revealAll() {
      Array.prototype.forEach.call(els, function (el) { el.classList.add('is-in'); });
    }
    // Bail out entirely rather than hide anything we might not be able to show.
    if (reduceMotion || !('IntersectionObserver' in window) || !els.length) return;

    document.documentElement.classList.add('js-reveal');

    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (en.isIntersecting) { en.target.classList.add('is-in'); io.unobserve(en.target); }
      });
    }, { rootMargin: '0px 0px -8% 0px', threshold: 0.06 });
    Array.prototype.forEach.call(els, function (el) { io.observe(el); });

    // Safety net: if the observer never fires (zero-size viewport, odd embed,
    // print, headless capture), show everything rather than leave a blank page.
    setTimeout(function () {
      if (!document.querySelectorAll('.reveal.is-in').length) { io.disconnect(); revealAll(); }
    }, 2500);
    window.addEventListener('beforeprint', revealAll);
  }());

}());
